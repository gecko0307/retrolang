/**
 * VLC decoder for STR video frames (bitstream version 2).
 *
 * Converts the variable-length-coded frame bitstream into the stream of 16-bit
 * run/level codes that the MDEC consumes (see mdec.r). Only BS v2 is supported.
 *
 * Bitstream layout (16-bit little-endian words, bits read MSB first):
 *   header, 8 bytes: [MDEC code count / 2] [0x3800] [quant scale] [version = 2]
 *   macroblocks, 6 blocks each: Cr, Cb, Y1, Y2, Y3, Y4
 *   block: 10-bit signed DC, then AC codes, then end-of-block ('10')
 *   AC code: MPEG-1 run/level VLC + sign bit, or escape '000001' + 6-bit run
 *            + 10-bit signed level
 *
 * The decoder is resumable: vlcBegin() starts a frame and vlcStep() decodes a
 * limited number of blocks per call, so the caller can service the CD-ROM or do
 * other work between the steps. vlcDecode() decodes a whole frame in one call.
 *
 * The lookup tables are generated and verified by vlcgen.py.
 */

