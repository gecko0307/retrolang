{
    ushort* hdr = (ushort*)job->src;

    if (job->srcBytes < 12 || job->dstWords < 128)
        return -1;
    if (hdr[1] != 0x3800 || hdr[3] != 2)
        return -1;

    vlcQ = (hdr[2] & 0x3f) << 10;
    vlcSrc = hdr + 4;
    vlcSrcEnd = hdr + (job->srcBytes >> 1);
    vlcDstStart = (ushort*)job->dst;
    vlcDst = vlcDstStart;
    // keep room for the padding added by vlcFinish (up to 31 words)
    vlcDstEnd = vlcDstStart + job->dstWords * 2 - 64;
    vlcBlocksLeft = ((job->width + 15) >> 4) * ((job->height + 15) >> 4) * 6;
    vlcWin = 0;
    vlcCnt = 0;
    vlcOutWords = 0;
    return 0;
}

// Pads the output to a whole word and then to a multiple of 32 words.
void vlcFinish()
{
    uint half = ((uint)vlcDst - (uint)vlcDstStart) >> 1;
    uint* p;
    int words;

    if ((half & 1) != 0)
    {
        *vlcDst = 0xfe00;
        vlcDst += 1;
        half += 1;
    }

    words = half >> 1;
    vlcOutWords = words;

    p = (uint*)vlcDst;
    while ((words & 31) != 0)
    {
        *p = 0;
        p += 1;
        words += 1;
    }
}

/**
 * Decodes up to the given number of blocks (6 blocks = 1 macroblock).
 * Returns 0 if there is more to decode, 1 when the frame is complete
 * (the result is in the output buffer, its size in vlcOutWords),
 * -1 on error (corrupt data or the output buffer is too small).
 *
 * This is the hot loop of the player, so it is written with 8 variables at
 * most (including the argument): RLC keeps only $s0-$s7 in registers, the
 * others would live in the stack frame, and every access to it is a RAM read
 * (there is no data cache). The bit window and the pointers are loaded once
 * per call, not per block.
 */
int vlcStep(int count)
{
    uint win = vlcWin;
    int cnt = vlcCnt;
    ushort* src = vlcSrc;
    ushort* dst = vlcDst;
    uint e;
    uint t;
    int k;

    if (count > vlcBlocksLeft)
        count = vlcBlocksLeft;
    vlcBlocksLeft = vlcBlocksLeft - count;

    while (count > 0)
    {
        // a block writes at most 65 halfwords
        if (dst + 66 > vlcDstEnd)
            return -1;
        if (src > vlcSrcEnd + 2)
            return -1;

        // Keep at least 17 bits in the window: the longest code (16) plus a sign.
        while (cnt <= 16)
        {
            win = win | ((uint)(*src) << (16 - cnt));
            src += 1;
            cnt += 16;
        }

        // DC: 10 bits, stored as is
        *dst = vlcQ | (win >> 22);
        dst += 1;
        win = win << 10;
        cnt -= 10;

        k = 0;
        while (1)
        {
            while (cnt <= 16)
            {
                win = win | ((uint)(*src) << (16 - cnt));
                src += 1;
                cnt += 16;
            }

            t = win >> 24;
            e = vlcL1[t];
            if (e == VLC_LINK)
                e = vlcL2[(t << 8) | ((win >> 16) & 255)];

            if (e == 0)
                return -1; // invalid code

            t = e & 63;
            if (t == 0)
            {
                // End of block
                win = win << 2;
                cnt -= 2;
                *dst = 0xfe00;
                dst += 1;
                break;
            }

            if (t == 63)
            {
                // Escape: the next 16 bits are the MDEC code (6-bit run, 10-bit level)
                win = win << 6;
                cnt -= 6;
                while (cnt <= 16)
                {
                    win = win | ((uint)(*src) << (16 - cnt));
                    src += 1;
                    cnt += 16;
                }
                t = win >> 16;
                *dst = t;
                win = win << 16;
                cnt -= 16;
                k = k + (t >> 10) + 1;
            }
            else
            {
                // e = (code length << 11) | (run << 6) | level, then the sign bit
                t = e >> 11;
                if (((win << t) >> 31) != 0)
                    *dst = ((e & 0x7c0) << 4) | ((0 - (e & 63)) & 0x3ff);
                else
                    *dst = ((e & 0x7c0) << 4) | (e & 63);
                win = win << (t + 1);
                cnt -= t + 1;
                k = k + ((e >> 6) & 31) + 1;
            }
            dst += 1;

            // The block holds 64 coefficients: DC plus run + 1 per AC code
            if (k > 63)
                return -1;
        }

        count = count - 1;
    }

    vlcWin = win;
    vlcCnt = cnt;
    vlcSrc = src;
    vlcDst = dst;

    if (vlcBlocksLeft > 0)
        return 0;

    vlcFinish();
    return 1;
}

/**
 * Decodes a whole frame. Returns the size of the MDEC data in words,
 * or -1 on error.
 */
int vlcDecode(struct VlcJob* job)
{
    int r;

    if (vlcBegin(job) < 0)
        return -1;

    while (1)
    {
        r = vlcStep(64);
        if (r < 0)
            return -1;
        if (r > 0)
            return vlcOutWords;
    }

    return -1;
}

